#!/usr/bin/env node
/**
 * Zero-dependency bundler → dist/boids.html, and the offline manifest in sw.js.
 *
 * Inlines the ES-module graph rooted at src/main.js into a single classic
 * <script>, and every local stylesheet into a <style>, inside a copy of
 * index.html. The result is one self-contained file
 * that runs from file:// (double-click it, AirDrop it to a phone) with no
 * server and no network.
 *
 * Each module is wrapped in its own function scope, so module-private names
 * never collide. Imports become destructuring from the dependency's export
 * object; modules are emitted in dependency order.
 *
 * Supported module syntax (anything else fails the build loudly):
 *   import { a, b as c } from './relative.js';
 *   export function | async function | class | const | let | var <name> …
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const ENTRY = resolve(ROOT, 'src/main.js');
const OUTPUT = resolve(ROOT, 'dist/boids.html');
const SERVICE_WORKER = resolve(ROOT, 'sw.js');
const GENERATED_START = '// ── Generated by scripts/build.mjs (npm run build). Do not edit by hand. ──';
const GENERATED_END = '// ── End of generated section ──';

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*(['"])(\.{1,2}\/[^'"]+)\2\s*;?[ \t]*$/gm;
const EXPORT_DECL_RE = /^export\s+(?:async\s+function\*?|function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;
const EXPORT_KEYWORD_RE = /^export\s+(?=(?:async\s+)?function|class|const|let|var)/gm;

/** @param {string} file */
const rel = (file) => relative(ROOT, file).split('\\').join('/');

/**
 * @typedef {object} ParsedModule
 * @property {string} file
 * @property {string} source
 * @property {{ file: string, specifiers: string }[]} imports
 * @property {string[]} exports
 */

/**
 * @param {string} source
 * @param {string} file
 * @returns {ParsedModule}
 */
function parseModule(source, file) {
  /** @type {ParsedModule['imports']} */
  const imports = [];
  for (const m of source.matchAll(IMPORT_RE)) {
    const specifiers = m[1]
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => s.replace(/\s+as\s+/, ': '))
      .join(', ');
    imports.push({ file: resolve(dirname(file), m[3]), specifiers });
  }
  // Anything import-like at the start of a line that the pattern above did not
  // consume is unsupported syntax (default/namespace/side-effect imports).
  const leftover = source.replace(IMPORT_RE, '').match(/^import[\s{*'"]/m);
  if (leftover) throw new Error(`${rel(file)}: unsupported import syntax near "${leftover[0]}"`);
  const badExport = source.match(/^export\s+(default\b|\*|\{)/m);
  if (badExport) throw new Error(`${rel(file)}: unsupported export syntax "${badExport[0]}"`);
  const exports = [...source.matchAll(EXPORT_DECL_RE)].map((m) => m[1]);
  return { file, source, imports, exports };
}

/**
 * Bundle the module graph into one classic script.
 * @param {string} [entry]
 * @returns {Promise<string>}
 */
export async function bundle(entry = ENTRY) {
  /** @type {Map<string, ParsedModule>} */
  const modules = new Map();
  /** @type {string[]} dependency order */
  const order = [];
  const visiting = new Set();

  /** @param {string} file */
  async function visit(file) {
    if (modules.has(file)) return;
    if (visiting.has(file)) throw new Error(`circular import involving ${rel(file)}`);
    visiting.add(file);
    const parsed = parseModule(await readFile(file, 'utf8'), file);
    for (const dep of parsed.imports) await visit(dep.file);
    visiting.delete(file);
    modules.set(file, parsed);
    order.push(file);
  }
  await visit(entry);

  const ids = new Map(order.map((file, i) => [file, `__module${i}`]));
  const chunks = order.map((file) => {
    const mod = /** @type {ParsedModule} */ (modules.get(file));
    const header = mod.imports.map((dep) => `const { ${dep.specifiers} } = ${ids.get(dep.file)};`).join('\n');
    const body = mod.source.replace(IMPORT_RE, '').replace(EXPORT_KEYWORD_RE, '').trim();
    return [
      `// ── ${rel(file)} ${'─'.repeat(Math.max(0, 66 - rel(file).length))}`,
      `const ${ids.get(file)} = (() => {`,
      header,
      body,
      `return { ${mod.exports.join(', ')} };`,
      '})();',
    ]
      .filter((line) => line !== '')
      .join('\n');
  });
  return [
    '// Generated by scripts/build.mjs from src/. Do not edit; run `npm run build`.',
    '(() => {',
    "'use strict';",
    ...chunks,
    '})();',
  ].join('\n');
}

/**
 * Produce the standalone HTML document.
 * @returns {Promise<string>}
 */
export async function buildStandalone() {
  const html = await readFile(resolve(ROOT, 'index.html'), 'utf8');
  const icon = await readFile(resolve(ROOT, 'icons/icon.svg'), 'utf8');
  const script = (await bundle()).replaceAll('</script', '<\\/script');
  const iconHref = `data:image/svg+xml,${encodeURIComponent(icon.trim())}`;
  const tag = '<script type="module" src="./src/main.js"></script>';
  if (!html.includes(tag)) throw new Error(`index.html must contain ${tag}`);
  // Inline local stylesheets.
  const stylesheets = [...html.matchAll(/<link rel="stylesheet" href="\.\/([^"]+)">/g)];
  let page = html;
  for (const [linkTag, href] of stylesheets) {
    const css = (await readFile(resolve(ROOT, href), 'utf8')).replaceAll('</style', '<\\/style').trim();
    page = page.replace(linkTag, () => `<style>\n${css}\n  </style>`);
  }
  return page
    .replace(/[ \t]*<!-- dev-only:start -->[\s\S]*?<!-- dev-only:end -->\n?/g, '')
    .replace(/[ \t]*<!-- hosted-only:start -->[\s\S]*?<!-- hosted-only:end -->\n?/g, '')
    .replace('</title>', `</title>\n  <link rel="icon" href="${iconHref}">`)
    .replace(tag, () => `<script>\n${script}\n  </script>`);
}

/**
 * Every file of the hosted app, as './…' paths relative to the project root:
 * the page, manifest, icons, every module and stylesheet, and the single-file
 * build (so its download works offline too). Sorted, so the output is stable.
 * @returns {Promise<string[]>}
 */
async function appFiles() {
  const files = ['./index.html', './manifest.webmanifest', './dist/boids.html'];
  for (const name of await readdir(resolve(ROOT, 'icons'))) files.push(`./icons/${name}`);
  /** @param {string} dir */
  const walk = async (dir) => {
    for (const entry of await readdir(resolve(ROOT, dir), { withFileTypes: true })) {
      const path = `${dir}/${entry.name}`;
      if (entry.isDirectory()) await walk(path);
      else if (/\.(?:js|css)$/.test(entry.name)) files.push(`./${path}`);
    }
  };
  await walk('src');
  return files.sort();
}

/**
 * sw.js with its generated section brought up to date: the list of app files
 * with the SHA-256 of each file's content, and a version derived from all of
 * them and from the worker's own code. The worker checks the one-time download
 * against these hashes, and a device frozen at one version refuses any other.
 * @param {string} [standalone] The single-file build, if already built.
 * @returns {Promise<string>}
 */
export async function buildServiceWorker(standalone) {
  const html = standalone ?? (await buildStandalone());
  /** @type {[string, string][]} */
  const entries = [];
  for (const file of await appFiles()) {
    const bytes = file === './dist/boids.html' ? Buffer.from(html) : await readFile(resolve(ROOT, file));
    entries.push([file, createHash('sha256').update(bytes).digest('base64')]);
  }
  const source = await readFile(SERVICE_WORKER, 'utf8');
  const start = source.indexOf(GENERATED_START);
  const end = source.indexOf(GENERATED_END);
  if (start < 0 || end < start) throw new Error('sw.js: generated section markers not found');
  // The worker's own code is part of the version too: devices frozen at one
  // version refuse any other, including a changed worker.
  const logic = source.slice(0, start) + source.slice(end + GENERATED_END.length);
  const version = createHash('sha256')
    .update(entries.map(([file, hash]) => `${file} ${hash}\n`).join(''))
    .update(`sw.js ${createHash('sha256').update(logic).digest('base64')}\n`)
    .digest('hex')
    .slice(0, 10);
  const generated = [
    GENERATED_START,
    `const VERSION = '${version}';`,
    '/** Every file of this version, with the SHA-256 (base64) of its exact content. */',
    'const FILES = {',
    ...entries.map(([file, hash]) => `  '${file}': '${hash}',`),
    '};',
    GENERATED_END,
  ].join('\n');
  return source.slice(0, start) + generated + source.slice(end + GENERATED_END.length);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const html = await buildStandalone();
  await mkdir(dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, html);
  console.log(`Wrote ${rel(OUTPUT)} (${(html.length / 1024).toFixed(1)} KiB): open it directly, no server needed.`);
  const sw = await buildServiceWorker(html);
  await writeFile(SERVICE_WORKER, sw);
  const version = sw.match(/const VERSION = '([^']+)'/)?.[1];
  console.log(`Wrote sw.js: offline version ${version}, ${(sw.match(/^  '\.\//gm) ?? []).length} files.`);
}
